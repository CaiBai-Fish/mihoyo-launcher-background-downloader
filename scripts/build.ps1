#requires -Version 5.1
<#
.SYNOPSIS
    构建 dmbg.exe（MSVC，直接调用 cl.exe，无需 CMake 生成器）。

.DESCRIPTION
    自动通过 vswhere 定位 Visual Studio 的 C++ 工具链并导入 vcvars64 环境，
    再用 cl.exe 编译到 build\ 目录。若机器上有 cmake，也可以用
    `cmake -S . -B build -G Ninja` 走 CMakeLists.txt，两条路等价。

.EXAMPLE
    pwsh -File scripts\build.ps1
    pwsh -File scripts\build.ps1 -Clean
#>
[CmdletBinding()]
param(
    [ValidateSet('Release', 'Debug')]
    [string]$Configuration = 'Release',
    [switch]$Clean
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root = Split-Path -Parent $PSScriptRoot
$outDir = Join-Path $root 'build'
$sources = @(
    (Join-Path $root 'src\main.cpp'),
    (Join-Path $root 'src\url_scanner.cpp'),
    (Join-Path $root 'src\http_client.cpp')
)

function Get-MsvcEnvironment {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (-not (Test-Path -LiteralPath $vswhere)) {
        throw "找不到 vswhere.exe。请安装 Visual Studio 的「使用 C++ 的桌面开发」工作负载。"
    }

    # -all, not -latest: an install whose state is "incomplete" (for example a
    # Visual Studio that finished installing its compiler but not every optional
    # component) is skipped by -latest even though the C++ toolchain works. We
    # therefore enumerate every candidate and pick the first one that actually
    # has vcvars64.bat on disk.
    $candidates = @(& $vswhere -all -prerelease -products * `
            -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 `
            -property installationPath)
    if (-not $candidates -or $candidates.Count -eq 0) {
        $candidates = @(& $vswhere -all -prerelease -products * -property installationPath)
    }
    if (-not $candidates -or $candidates.Count -eq 0) {
        throw "vswhere 未找到任何 Visual Studio 安装。请安装「使用 C++ 的桌面开发」工作负载。"
    }

    $installation = $null
    $vcvars = $null
    foreach ($candidate in $candidates) {
        if (-not $candidate) { continue }
        $probe = Join-Path $candidate.Trim() 'VC\Auxiliary\Build\vcvars64.bat'
        if (Test-Path -LiteralPath $probe) {
            $installation = $candidate.Trim()
            $vcvars = $probe
            break
        }
    }
    if (-not $vcvars) {
        throw "找到了 Visual Studio 安装，但都没有 vcvars64.bat（缺少 C++ 工具集）: $($candidates -join ', ')"
    }

    Write-Host "使用 Visual Studio: $installation" -ForegroundColor Cyan

    $dump = cmd /c "call `"$vcvars`" >nul 2>&1 && set"
    $env_vars = @{}
    foreach ($line in $dump) {
        $separator = $line.IndexOf('=')
        if ($separator -gt 0) {
            $env_vars[$line.Substring(0, $separator)] = $line.Substring($separator + 1)
        }
    }
    return $env_vars
}

Push-Location $root
try {
    if ($Clean -and (Test-Path -LiteralPath $outDir)) {
        Write-Host "清理 $outDir" -ForegroundColor Yellow
        Remove-Item -LiteralPath $outDir -Recurse -Force
    }
    if (-not (Test-Path -LiteralPath $outDir)) {
        New-Item -ItemType Directory -Path $outDir | Out-Null
    }

    $msvc = Get-MsvcEnvironment
    foreach ($name in @('INCLUDE', 'LIB', 'LIBPATH', 'PATH')) {
        if (-not $msvc.ContainsKey($name)) {
            throw "vcvars64 环境缺少 $name，工具链不完整。"
        }
        Set-Item -Path "env:$name" -Value $msvc[$name]
    }

    $cl = Get-Command cl.exe -ErrorAction SilentlyContinue
    if (-not $cl) {
        throw "PATH 中仍然找不到 cl.exe。"
    }
    Write-Host "编译器: $($cl.Source)" -ForegroundColor Cyan

    foreach ($source in $sources) {
        if (-not (Test-Path -LiteralPath $source)) {
            throw "缺少源文件: $source"
        }
    }

    $version = (Select-String -Path (Join-Path $root 'CMakeLists.txt') `
            -Pattern 'VERSION\s+([0-9]+\.[0-9]+\.[0-9]+)' |
            Select-Object -First 1).Matches[0].Groups[1].Value
    if (-not $version) { $version = '0.0.0' }

    # The version travels through a generated header, not through /D. PowerShell
    # strips the inner quotes of an argument like /DDMBG_VERSION="1.0.0" when it
    # builds the native command line, which turns the macro into `1.0.0` and the
    # build fails with confusing "std::string + double" errors.
    $generatedDir = Join-Path $outDir 'generated'
    if (-not (Test-Path -LiteralPath $generatedDir)) {
        New-Item -ItemType Directory -Path $generatedDir | Out-Null
    }
    $versionHeader = Join-Path $generatedDir 'version.h'
    $versionContent = @(
        '#pragma once'
        '// Generated by scripts/build.ps1 from the version in CMakeLists.txt. Do not edit.'
        "#define DMBG_VERSION `"$version`""
    ) -join "`r`n"
    [System.IO.File]::WriteAllText($versionHeader, $versionContent + "`r`n",
        (New-Object System.Text.UTF8Encoding($false)))

    $flags = [System.Collections.Generic.List[string]]::new()
    $flags.Add('/nologo')
    $flags.Add('/std:c++17')
    $flags.Add('/utf-8')
    $flags.Add('/EHsc')
    $flags.Add('/W4')
    $flags.Add('/permissive-')
    $flags.Add('/D_UNICODE')
    $flags.Add('/DUNICODE')
    # windows.h defines min/max as macros, which breaks std::min / std::max.
    $flags.Add('/DNOMINMAX')
    $flags.Add('/I' + (Join-Path $root 'src'))
    $flags.Add('/I' + $generatedDir)
    if ($Configuration -eq 'Debug') {
        $flags.Add('/Od')
        $flags.Add('/Zi')
        $flags.Add('/MDd')
        $flags.Add('/RTC1')
    } else {
        $flags.Add('/O2')
        $flags.Add('/MD')
        $flags.Add('/DNDEBUG')
    }
    $flags.Add('/Fo' + $outDir + '\')
    $flags.Add('/Fe' + (Join-Path $outDir 'dmbg.exe'))

    # user32: SetProcessDpiAwarenessContext. winhttp: HTTP. shell32: ShellExecuteW.
    # ole32: COM / IFileDialog. comdlg32: common dialog base types.
    $libraries = @('winhttp.lib', 'shell32.lib', 'ole32.lib', 'comdlg32.lib', 'user32.lib')

    Write-Host "编译 ($Configuration)..." -ForegroundColor Cyan
    $arguments = @($flags) + $sources + @('/link') + $libraries
    $output = & cl.exe @arguments 2>&1
    $exitCode = $LASTEXITCODE
    $output | ForEach-Object { Write-Host $_ }

    if ($exitCode -ne 0) {
        throw "编译失败，退出码 $exitCode"
    }

    $exe = Join-Path $outDir 'dmbg.exe'
    if (-not (Test-Path -LiteralPath $exe)) {
        throw "编译报告成功但没有产出 $exe"
    }

    $size = [math]::Round((Get-Item -LiteralPath $exe).Length / 1KB, 1)
    Write-Host ""
    Write-Host "构建成功: $exe ($size KB, 版本 $version)" -ForegroundColor Green
    & $exe --version
    Write-Host ""
    Write-Host "试试: $exe --help" -ForegroundColor Green
} finally {
    Pop-Location
}
